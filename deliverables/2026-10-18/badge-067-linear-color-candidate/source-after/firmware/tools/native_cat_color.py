"""Shared production color transform; generated assets are candidates for user selection."""
from pathlib import Path
import hashlib
import json
import numpy as np


class NativeCatColor:
    def __init__(self, path):
        self.raw = Path(path).read_bytes()
        self.profile = json.loads(self.raw)
        self.sha256 = hashlib.sha256(self.raw).hexdigest()
        if self.profile['schemaVersion'] != 1:
            raise ValueError('Unsupported native cat color profile')
        self.lighting = self.profile['lighting']
        self.levels = self.lighting['linearLevels']
        if len(self.levels) != 3:
            raise ValueError('Existing native layer format requires three light levels')

    def decode(self, srgb):
        t = self.profile['transfer']
        c = np.asarray(srgb, dtype=float) / 255.0
        return np.where(c <= t['decodeThreshold'], c / t['linearScale'],
                        ((c + t['offset']) / t['scale']) ** t['gamma'])

    def encode(self, linear):
        t = self.profile['transfer']
        c = np.clip(linear, 0, 1)
        srgb = np.where(c <= t['encodeThreshold'], c * t['linearScale'],
                        t['scale'] * c ** (1 / t['gamma']) - t['offset'])
        return np.clip(np.rint(srgb * 255), 0, 255).astype(np.uint32)

    def shade(self, linear, level):
        t = self.profile['toneMapping']
        c = np.asarray(linear) * self.levels[level] * t['exposure'] / t['exposureNormalization']
        c = c @ np.asarray(t['inputMatrixRows']).T
        n, d = t['rrtOdtNumerator'], t['rrtOdtDenominator']
        c = (c * (c + n[0]) + n[1]) / (c * (d[0] * c + d[1]) + d[2])
        return self.encode(c @ np.asarray(t['outputMatrixRows']).T)

    def srgb_shades(self, srgb, factor=(1, 1, 1)):
        linear = self.decode(srgb) * np.asarray(factor)
        return np.stack([self.shade(linear, level) for level in range(3)])

    def write_breed_lookup(self, output):
        """Preserve existing role/age selection; precompute the full RGB transform.

        A three-channel ACES matrix cannot be replaced with independent channel
        gamma tables. Store complete final RGB values instead of runtime floats.
        """
        p = self.profile['alternateBreedPalette']
        rows = []
        for amount in p['growthTintPercent']:
            breeds = []
            for palette in p['colors']:
                roles = []
                for role, source in enumerate([palette[0], palette[2], palette[3], int(p['blueEye'], 16)]):
                    channels = np.array([(source >> shift) & 255 for shift in [16, 8, 0]], dtype=int)
                    tint = int(amount * p['creamTintScale']) if role == 2 else amount
                    if role != 3:
                        channels = (channels + (255 - channels) * tint // 100 if tint >= 0
                                    else channels * (100 + tint) // 100)
                    colors = self.srgb_shades(channels)
                    roles.append([int(0xff000000 | int(c[0]) << 16 | int(c[1]) << 8 | int(c[2])) for c in colors])
                breeds.append(roles)
            rows.append(breeds)
        def c_array(value):
            return '{' + ','.join(c_array(v) if isinstance(v, list) else hex(v) + 'u' for v in value) + '}'
        text = ('/* Generated by pack_native_cat.py; candidate final sRGB colors. */\n'
                '#pragma once\n#include <stdint.h>\n'
                '#define BADGE_NATIVE_COLOR_PROFILE "' + self.profile['id'] + '"\n'
                '#define BADGE_NATIVE_COLOR_PROFILE_SHA256 "' + self.sha256 + '"\n'
                'static const uint32_t badge_native_breed_colors[3][9][4][3]=' + c_array(rows) + ';\n')
        (output / 'native_cat_color.h').write_text(text)
