#!/usr/bin/env python3
"""Supplement original fonts with complete same-size known repertoire, offline/OFL."""
from pathlib import Path
import re,json,hashlib,ast
from PIL import ImageFont, __version__ as pillow_version
OUT=Path(__file__).resolve().parents[1]; ROOT=OUT.parents[1]; SRC=OUT/'source'
FONT=ROOT/'firmware/managed_components/lvgl__lvgl/scripts/built_in_font/SourceHanSansSC-Normal.otf'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def coverage(p):
 s=p.read_text(); arrays={name:[int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+',values)] for name,values in re.findall(r'static const uint16_t (unicode_list_\d+)\[\]\s*=\s*\{(.*?)\};',s,re.S)}
 cps=set()
 for part in re.findall(r'\{\s*\.range_start\s*=.*?\}',s,re.S):
  fields=dict(re.findall(r'\.(\w+)\s*=\s*([^,}\n]+)',part));start=int(fields['range_start'],0);length=int(fields['range_length'],0)
  cps.update(start+v for v in arrays[fields['unicode_list'].strip()]) if fields['unicode_list'].strip()!='NULL' else cps.update(range(start,start+length))
 return cps
known=set(); old={}
for size in (16,20,24):old[size]=coverage(SRC/f'main/assets/badge_f{size}.c');known|=old[size]
inputs={}
for p in list((SRC/'main').glob('*.c'))+list((SRC/'main').glob('*.inc')):
 inputs[str(p.relative_to(SRC))]=sha(p)
 for text in re.findall(r'"(?:[^"\\]|\\.)*"',p.read_text()):
  try:known.update(ord(c) for c in ast.literal_eval(text) if ord(c)>=32 and ord(c)!=127)
  except (ValueError,SyntaxError):pass
known.add(0x54aa)
probe=ImageFont.truetype(str(FONT),24); notdef=(bytes(probe.getmask(chr(0x10ffff))),probe.getlength(chr(0x10ffff))); missing={cp for cp in known if (bytes(probe.getmask(chr(cp))),probe.getlength(chr(cp)))==notdef}
if missing:raise SystemExit('OFL font lacks '+str(sorted(missing)))
body='/* Generated by tools/generate_same_size_fonts.py. Source Han Sans SC, SIL OFL1.1. */\n';records=[]
for size,line,base in ((16,19,4),(20,23,5),(24,30,7)):
 cps=sorted(known-old[size]);font=ImageFont.truetype(str(FONT),size);prefix=f'local2_extra{size}';data=[];glyphs=['{0}'];topmax=bottommax=0
 for cp in cps:
  ch=chr(cp);mask,(left,top)=font.getmask2(ch,mode='L',anchor='ls');w,h=mask.size;vals=[(int(v)*15+127)//255 for v in mask]
  if len(vals)%2:vals.append(0)
  glyphs.append('{ .bitmap_index=%d, .adv_w=%d, .box_w=%d, .box_h=%d, .ofs_x=%d, .ofs_y=%d }'%(len(data),round(font.getlength(ch)*16),w,h,left,-(top+h)))
  data.extend((vals[i]<<4)|vals[i+1] for i in range(0,len(vals),2));topmax=max(topmax,-top);bottommax=max(bottommax,top+h)
 body+=f'static const uint8_t {prefix}_bitmap[]={{\n'+''.join(' '+','.join(map(str,data[i:i+24]))+',\n' for i in range(0,len(data),24))+'};\n'
 body+=f'static const lv_font_fmt_txt_glyph_dsc_t {prefix}_glyphs[]={{\n'+',\n'.join(glyphs)+'\n};\n'
 start=cps[0];body+=f'static const uint16_t {prefix}_unicode[]={{'+','.join(str(cp-start) for cp in cps)+'};\n'
 body+=f'''static const lv_font_fmt_txt_cmap_t {prefix}_cmap[]={{
 {{.range_start={start},.range_length={cps[-1]-start+1},.glyph_id_start=1,.unicode_list={prefix}_unicode,.glyph_id_ofs_list=NULL,.list_length={len(cps)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static const lv_font_fmt_txt_dsc_t {prefix}_dsc={{.glyph_bitmap={prefix}_bitmap,.glyph_dsc={prefix}_glyphs,.cmaps={prefix}_cmap,.kern_dsc=NULL,.kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0}};
static const lv_font_t {prefix}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={line},.base_line={base},.subpx=LV_FONT_SUBPX_NONE,.underline_position=-3,.underline_thickness=1,.dsc=&{prefix}_dsc,.fallback=NULL}};
'''
 records.append(dict(pixels=size,original_glyphs=len(old[size]),added_glyphs=len(cps),combined_glyphs=len(known),bitmap_bytes=len(data),line_height=line,base_line=base,max_above_baseline=topmax,max_below_baseline=bottommax,codepoints=cps))
p=SRC/'main/assets/local2_same_size_glyphs.inc';p.write_text(body)
report=dict(source=str(FONT.relative_to(ROOT)),source_sha256=sha(FONT),license='SIL Open Font License 1.1',license_path='source/main/assets/OFL-1.1.txt',license_sha256=sha(SRC/'main/assets/OFL-1.1.txt'),method='Pillow FreeType grayscale baseline ls; nearest linear 4bpp; original glyphs unchanged; additions only',pillow=pillow_version,input_hashes=inputs,known_codepoints=sorted(known),sizes=records,output_sha256=sha(p),all_known_same_size=True,no_cross_size_fallback=True,unbounded_future_remote_text_not_claimed=True)
(OUT/'evidence/font-generation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n');print([(r['pixels'],r['added_glyphs'],r['bitmap_bytes']) for r in records])
