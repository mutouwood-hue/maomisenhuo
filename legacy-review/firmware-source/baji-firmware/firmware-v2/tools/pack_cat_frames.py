"""Pack existing BGRA sheets into immutable, decoder-valid frame assets."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'render' / 'generated'


def generate():
    lines = ['/* Generated by tools/pack_cat_frames.py; BGRA bytes preserved. */', '#include "baji_assets.h"']
    for name, width, height in [('catA', 98, 113), ('catB', 87, 101)]:
        source = (OUT / (name + '.c')).read_text(encoding='utf-8')
        body = source.split('_pixels[] = {', 1)[1].split('};', 1)[0]
        sheet = bytes(int(v) for v in re.findall(r'\d+', body))
        stride = width * 24 * 4
        size = width * height * 4
        assert len(sheet) == stride * height
        packed = bytearray()
        for frame in range(24):
            data = b''.join(sheet[y * stride + frame * width * 4:y * stride + (frame + 1) * width * 4] for y in range(height))
            assert len(data) == size and any(data[3::4])
            for y in range(height):
                assert data[y * width * 4:(y + 1) * width * 4] == sheet[y * stride + frame * width * 4:y * stride + (frame + 1) * width * 4]
            packed.extend(data)
        symbol = 'bj_frames_' + name
        lines.append(f'static const uint8_t {symbol}_pixels[] = {{')
        lines.extend(','.join(str(v) for v in packed[i:i+32]) + ',' for i in range(0, len(packed), 32))
        lines.extend(['};', f'const lv_image_dsc_t {symbol}[24] = {{'])
        for frame in range(24):
            lines.append(f' {{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w={width},.h={height},.stride={width*4}}},.data_size={size},.data={symbol}_pixels+{frame*size}}},')
        lines.append('};')
        print(f'PASS {name}: 24 nonblank BGRA frames, exact row preservation, stride={width*4}, size={size}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    import sys
    text = generate()
    target = OUT / 'cat_frames.c'
    if '--check' in sys.argv:
        assert target.read_text(encoding='utf-8') == text, 'Packed assets are stale'
        print('PASS generated frame descriptors and bytes match source sheets')
    else:
        target.write_text(text, encoding='utf-8')
