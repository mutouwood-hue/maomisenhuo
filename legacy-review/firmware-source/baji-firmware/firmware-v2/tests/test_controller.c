#include "baji_controller.h"
#include "baji_composition.h"
#include <stdio.h>
static unsigned n, failed;
#define CHECK(x) do {n++;if(!(x)){failed++;printf("FAIL %d %s\n",__LINE__,#x);}}while(0)
int main(void) {
    bj_controller_t c;bj_controller_init(&c);
    CHECK(bj_scene_start_local(&c.scene));
    bj_controller_press(&c,248,262,0);
    CHECK(bj_controller_frame(&c,0).autonomous_paused);
    bj_controller_release(&c,248,262,100,false);bj_controller_tick(&c,1000);
    CHECK(c.scene.step==1);
    bj_controller_press(&c,233,404,1100);bj_controller_move(&c,233,236,1200);
    bj_frame_t f=bj_controller_frame(&c,1200);
    CHECK(f.source.screen==BJ_GUIDE && f.target.screen==BJ_CARE);
    CHECK(f.source_y==-168 && f.target_y==298 && f.target_visible);
    CHECK(c.scene.screen==BJ_GUIDE && c.scene.phase==BJ_GUIDE_DO);
    bj_controller_release(&c,233,236,1300,false);
    CHECK(c.motion==BJ_COMMIT && c.scene.screen==BJ_GUIDE);
    f=bj_controller_frame(&c,1300+c.duration/2);
    CHECK(f.source_y<-168 && f.source_y>-466);
    CHECK(f.target_y-f.source_y==466);
    bj_controller_tick(&c,1300+c.duration);
    CHECK(c.scene.screen==BJ_CARE && c.scene.phase==BJ_GUIDE_BACK);
    bj_controller_press(&c,233,100,1500);bj_controller_move(&c,233,200,1600);
    f=bj_controller_frame(&c,1600);
    CHECK(f.target.screen==BJ_GUIDE && f.target.phase==BJ_GUIDE_DO);
    CHECK(c.scene.phase==BJ_GUIDE_BACK);
    bj_controller_release(&c,233,200,1650,true);
    CHECK(c.motion==BJ_CANCEL);
    bj_controller_tick(&c,1830);CHECK(c.scene.screen==BJ_CARE);
    bj_controller_press(&c,233,100,1900);bj_controller_release(&c,233,260,2000,false);
    CHECK(c.motion==BJ_COMMIT);
    bj_controller_press(&c,233,233,2010);
    CHECK(c.scene.screen==BJ_GUIDE && c.scene.phase==BJ_GUIDE_OK);
    CHECK(c.gesture.pressed && c.motion==BJ_INPUT_NONE);
    bj_controller_release(&c,233,233,2020,true);bj_controller_tick(&c,3000);
    CHECK(c.scene.step==2);
    bj_controller_press(&c,100,200,3100);bj_controller_move(&c,300,200,3200);
    f=bj_controller_frame(&c,3200);
    CHECK(!f.target_visible && f.source_x==28);
    bj_controller_release(&c,300,200,3300,false);CHECK(c.motion==BJ_RUBBER);
    bj_controller_tick(&c,3500);CHECK(c.scene.screen==BJ_GUIDE);
    f=bj_controller_frame(&c,3500);
    CHECK(f.source_x==0 && f.source_y==0 && !f.target_visible);
    CHECK(!f.autonomous_paused);
    /* Suspend interrupts a pending commit, never resolves it like fresh press. */
    bj_controller_init(&c);CHECK(bj_scene_start_local(&c.scene));c.scene.step=1;
    bj_controller_press(&c,233,400,0);bj_controller_release(&c,233,200,100,false);
    CHECK(c.motion==BJ_COMMIT);
    bj_controller_set_suspended(&c,true,110);
    CHECK(c.suspended && c.motion==BJ_INPUT_NONE && !c.gesture.pressed);
    CHECK(c.scene.screen==BJ_GUIDE && c.scene.step==1);
    f=bj_controller_frame(&c,120);
    CHECK(f.autonomous_paused && !f.target_visible && f.source_y==0);
    bj_controller_press(&c,248,262,200);bj_controller_move(&c,233,0,300);
    bj_controller_release(&c,233,0,400,false);bj_controller_tick(&c,10000);
    CHECK(!c.gesture.pressed && c.scene.screen==BJ_GUIDE);
    bj_controller_set_suspended(&c,false,10000);
    bj_controller_release(&c,233,0,10001,false);
    CHECK(c.motion==BJ_INPUT_NONE && c.scene.step==1);
    bj_controller_press(&c,233,400,10100);bj_controller_move(&c,233,250,10200);
    bj_controller_set_suspended(&c,true,10210);
    CHECK(!c.gesture.pressed && bj_controller_frame(&c,10210).source_y==0);
    bj_controller_set_suspended(&c,false,10300);
    bj_controller_press(&c,233,400,10400);bj_controller_release(&c,233,200,10500,false);
    bj_controller_tick(&c,11000);CHECK(c.scene.screen==BJ_CARE);
    bj_controller_set_suspended(&c,true,11001);
    CHECK(c.scene.screen==BJ_CARE && c.scene.phase==BJ_GUIDE_BACK && c.scene.back_direction==BJ_DOWN);
    /* Actual hold cancelled by safety is not successful voice teaching. */
    bj_controller_init(&c);CHECK(bj_scene_start_local(&c.scene));c.scene.step=4;
    bj_controller_press(&c,233,233,0);bj_controller_tick(&c,600);
    CHECK(c.scene.screen==BJ_VOICE);
    bj_controller_set_suspended(&c,true,650);
    CHECK(c.scene.screen==BJ_GUIDE && !c.scene.voice_success_pending && !c.gesture.pressed);
    bj_controller_set_suspended(&c,false,10000);bj_controller_tick(&c,11000);
    CHECK(c.scene.phase==BJ_GUIDE_DO && c.scene.step==4);
    bj_controller_press(&c,233,233,12000);bj_controller_tick(&c,12600);
    bj_controller_release(&c,233,233,12700,false);
    CHECK(c.scene.voice_success_pending);
    bj_controller_set_suspended(&c,true,12710);bj_controller_set_suspended(&c,false,15000);
    bj_controller_tick(&c,16000);CHECK(!c.scene.voice_success_pending && c.scene.step==4);
    /* Successful phase retains remaining 800 ms; repeated suspend is idempotent. */
    bj_controller_init(&c);CHECK(bj_scene_start_local(&c.scene));
    bj_controller_press(&c,248,262,0);bj_controller_release(&c,248,262,100,false);
    bj_controller_set_suspended(&c,true,200);bj_controller_set_suspended(&c,true,400);
    bj_controller_tick(&c,10000);CHECK(c.scene.phase==BJ_GUIDE_OK && c.scene.step==0);
    bj_controller_set_suspended(&c,false,10200);bj_controller_set_suspended(&c,false,10300);
    bj_controller_tick(&c,10999);CHECK(c.scene.step==0);
    bj_controller_tick(&c,11000);CHECK(c.scene.step==1);
    /* uint32 clock wrap and identity preservation. */
    bj_controller_init(&c);CHECK(bj_scene_start_local(&c.scene));
    c.scene.phase=BJ_GUIDE_OK;c.scene.success_t0=UINT32_MAX-199;
    bj_controller_set_suspended(&c,true,UINT32_MAX-99);
    bj_controller_set_suspended(&c,false,100);
    bj_controller_tick(&c,899);CHECK(c.scene.step==0);
    bj_controller_tick(&c,900);CHECK(c.scene.step==1);
    CHECK(c.scene.local_experience && !c.scene.authenticated);
    bj_controller_init(&c);bj_scene_owner_verified(&c.scene);
    bj_controller_set_suspended(&c,true,0);bj_controller_set_suspended(&c,false,1000);
    CHECK(c.scene.authenticated && !c.scene.local_experience && c.scene.step==0);
    /* Four regular-page commits and both cancellation motions are interruptible. */
    const int end_x[]={233,233,33,433},end_y[]={33,433,233,233};
    for(unsigned i=0;i<4;i++) {
        bj_controller_init(&c);c.scene.screen=BJ_MAIN_A;
        bj_controller_press(&c,233,233,0);
        bj_controller_release(&c,end_x[i],end_y[i],100,false);
        CHECK(c.motion==BJ_COMMIT);
        bj_controller_set_suspended(&c,true,110);
        bj_controller_set_suspended(&c,false,1000);bj_controller_tick(&c,2000);
        f=bj_controller_frame(&c,2000);
        CHECK(c.scene.screen==BJ_MAIN_A && c.scene.face==0 && !f.target_visible && f.source_x==0 && f.source_y==0);
        CHECK(c.gesture.config.panel==466 && c.gesture.config.hold_ms==600);
    }
    bj_controller_init(&c);c.scene.screen=BJ_MAIN_A;
    bj_controller_press(&c,233,233,0);bj_controller_release(&c,233,200,100,false);
    CHECK(c.motion==BJ_CANCEL);
    bj_controller_set_suspended(&c,true,110);CHECK(c.motion==BJ_INPUT_NONE);
    bj_controller_init(&c);
    bj_controller_press(&c,233,233,0);bj_controller_release(&c,233,33,100,false);
    CHECK(c.motion==BJ_RUBBER);
    bj_controller_set_suspended(&c,true,110);CHECK(c.motion==BJ_INPUT_NONE);
    bj_composition_t plan=bj_composition_plan(NULL);
    CHECK(plan.source_opacity==255 && !plan.moving);
    for(int offset=-466;offset<=466;offset++) {
        f=(bj_frame_t){0};f.target_visible=true;f.source_y=offset;
        f.target_y=offset+(offset<=0?466:-466);
        plan=bj_composition_plan(&f);
        int distance=offset<0?-offset:offset;
        CHECK(plan.source_y==0 && plan.target_y==f.target_y && plan.target_visible);
        CHECK(plan.source_opacity==(distance>=210?0:(210-distance)*255/210));
        f.target_visible=false;plan=bj_composition_plan(&f);
        CHECK(plan.source_y==offset && plan.source_opacity==255 && !plan.target_visible);
        f.source_y=0;f.source_x=offset;f.target_x=offset+466;f.target_visible=true;
        plan=bj_composition_plan(&f);
        CHECK(plan.source_x==offset && plan.target_x==f.target_x && plan.source_opacity==255);
    }
    bj_controller_init(&c);c.scene.screen=BJ_MAIN_A;
    bj_controller_press(&c,233,233,0);bj_controller_move(&c,233,133,100);
    f=bj_controller_frame(&c,100);plan=bj_composition_plan(&f);
    CHECK(plan.source_y==0 && plan.source_opacity==133 && plan.target_y==366);
    bj_controller_release(&c,233,133,110,true);
    f=bj_controller_frame(&c,200);plan=bj_composition_plan(&f);
    CHECK(plan.source_y==0 && plan.source_opacity>133 && plan.source_opacity<255);
    bj_controller_tick(&c,290);f=bj_controller_frame(&c,290);plan=bj_composition_plan(&f);
    CHECK(plan.source_opacity==255 && !plan.target_visible && !plan.moving);
    bj_controller_init(&c);c.scene.screen=BJ_PAIR;
    bj_controller_press(&c,233,233,0);
    f=bj_controller_frame(&c,0);CHECK(!f.sliding);
    bj_controller_move(&c,233,200,10);bj_controller_move(&c,233,233,20);
    f=bj_controller_frame(&c,20);plan=bj_composition_plan(&f);
    CHECK(f.sliding && !f.target_visible && f.source_y==0 && plan.moving);
    bj_controller_release(&c,233,233,30,true);
    f=bj_controller_frame(&c,30);CHECK(f.sliding);
    bj_controller_tick(&c,230);f=bj_controller_frame(&c,230);
    CHECK(!f.sliding && !bj_composition_plan(&f).moving);
    bj_controller_press(&c,233,233,240);bj_controller_move(&c,200,233,250);
    bj_controller_set_suspended(&c,true,260);f=bj_controller_frame(&c,260);
    CHECK(!f.sliding && !bj_composition_plan(&f).moving);
    bj_scene_t back={0};back.tutorial_active=true;back.phase=BJ_GUIDE_BACK;back.back_enter_t0=1000;
    CHECK(bj_back_opacity(NULL,1000)==0);
    CHECK(bj_back_opacity(&back,999)==0);
    for(uint32_t dt=0;dt<=300;dt++) CHECK(bj_back_opacity(&back,1000+dt)==(dt>=250?255:dt*255/250));
    back.back_enter_t0=UINT32_MAX-100;
    CHECK(bj_back_opacity(&back,24)==127);
    back.phase=BJ_GUIDE_DO;CHECK(bj_back_opacity(&back,24)==0);
    back.phase=BJ_GUIDE_BACK;back.tutorial_active=false;CHECK(bj_back_opacity(&back,24)==0);
    bj_controller_init(&c);CHECK(bj_scene_start_local(&c.scene));c.scene.step=1;
    bj_controller_press(&c,233,404,1000);bj_controller_move(&c,233,236,1100);
    f=bj_controller_frame(&c,1100);CHECK(c.scene.back_enter_t0==0 && !bj_back_opacity(&f.target,1100));
    bj_controller_release(&c,233,236,1200,false);uint32_t entered=1200+c.duration;
    bj_controller_tick(&c,entered);CHECK(c.scene.back_enter_t0==entered && bj_back_opacity(&c.scene,entered)==0);
    CHECK(bj_back_opacity(&c.scene,entered+125)==127);
    bj_controller_press(&c,233,233,entered+130);bj_controller_move(&c,200,233,entered+140);
    bj_controller_release(&c,200,233,entered+150,true);bj_controller_tick(&c,entered+350);
    CHECK(c.scene.back_enter_t0==entered && bj_back_opacity(&c.scene,entered+350)==255);
    bj_controller_set_suspended(NULL,true,0);
    printf("v2 controller: %u checks, %u failures\n",n,failed);return failed?1:0;
}
