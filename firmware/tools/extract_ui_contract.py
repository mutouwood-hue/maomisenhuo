#!/usr/bin/env python3
"""Extract reviewed colors/timings from the original UI package, without hardware claims."""
from pathlib import Path
import hashlib
import json
import zipfile

root = Path(__file__).resolve().parents[2]
source = root / "吧唧交互规范开发包.zip"
with zipfile.ZipFile(source) as archive:
    raw = archive.read(next(n for n in archive.namelist() if n.endswith("/badge_spec.json")))
spec = json.loads(raw)
lines = ["/* Generated by firmware/tools/extract_ui_contract.py; original badge_spec.json v0.3.0. */",
         "#pragma once", "#include <stdint.h>"]
for name, value in spec["colors"].items():
    lines.append(f"#define ZIP_UI_COLOR_{name.upper()} 0x{value[1:]}")
for name in ("tapMaxMs", "tapMoveMax", "longPressMs", "swipeMinPx", "swipeMaxMs", "transitionMs"):
    lines.append(f"#define ZIP_UI_{name.upper()} {spec['timing'][name]}")
lines += [f"#define ZIP_UI_SAFE_R {spec['screen']['safeR']}",
          "static inline int16_t zip_ui_clamp(int16_t p) { return p < 0 ? 0 : (p > 465 ? 465 : p); }"]
(root / "firmware/main/badge_ui_contract.h").write_text("\n".join(lines) + "\n")
manifest = {"source": source.name, "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "specSha256": hashlib.sha256(raw).hexdigest(), "version": spec["version"],
            "screens": {k: {"name": v["name"], "gestures": v.get("gest", {})} for k, v in spec["screens"].items()},
            "note": "Only palette and basic touch thresholds are compiled; no hardware history, sample values or legacy events imported."}
(root / "firmware/main/assets/ui-contract-source.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
print("Extracted palette and 6 basic gesture timings; retained 23-screen source index")
