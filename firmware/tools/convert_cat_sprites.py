#!/usr/bin/env python3
"""Reproduce LVGL 9 RGB565A8 assets from the recovered original cat renders.

RGB565A8 stores the entire little-endian RGB565 plane, then the entire A8
plane; alpha stride is RGB stride / 2. This matches LVGL v9.5.0 LVGLImage.py.
No new art, recoloring, premultiplication, dithering or model generation.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[2]
FILES = ("cat-idle.png", "cat-paw.png")
WIDTH, HEIGHT = 200, 180
LAYOUT_SOURCE = "https://github.com/lvgl/lvgl/blob/v9.5.0/scripts/LVGLImage.py"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def encode(image: Image.Image) -> bytes:
    rgb, alpha = bytearray(), bytearray()
    pixels = image.tobytes()
    for r, g, b, a in zip(pixels[0::4], pixels[1::4], pixels[2::4], pixels[3::4]):
        color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb.extend(color.to_bytes(2, "little"))
        alpha.append(a)
    return bytes(rgb + alpha)


def c_source(symbol: str, data: bytes, input_sha: str) -> str:
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[n:n + 16]) + ","
            for n in range(0, len(data), 16)]
    return f'''/* Generated by firmware/tools/convert_cat_sprites.py. Do not edit.
 * Original PNG SHA-256: {input_sha}
 * Layout: RGB565 little endian plane, then A8 plane; no premultiplication.
 */
#include "lvgl.h"

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_pixels[] = {{
{chr(10).join(rows)}
}};

const lv_image_dsc_t {symbol} = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = LV_COLOR_FORMAT_RGB565A8,
    .header.flags = 0,
    .header.w = {WIDTH},
    .header.h = {HEIGHT},
    .header.stride = {WIDTH * 2},
    .data_size = sizeof({symbol}_pixels),
    .data = {symbol}_pixels,
}};
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=ROOT / "assets/rendering")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "firmware/main/assets")
    parser.add_argument("--check", action="store_true", help="Verify generated files without changing them")
    args = parser.parse_args()
    images = {name: Image.open(args.input_dir / name).convert("RGBA") for name in FILES}
    if any(im.size != (WIDTH, HEIGHT) for im in images.values()):
        raise SystemExit("Expected the reviewed original 200x180 renders")
    boxes = [im.getchannel("A").getbbox() for im in images.values()]
    if any(box is None for box in boxes):
        raise SystemExit("A source render is fully transparent")
    # One shared crop/scale keeps the original anchor identical across poses.
    crop = (max(0, min(b[0] for b in boxes) - 2), max(0, min(b[1] for b in boxes) - 2),
            min(WIDTH, max(b[2] for b in boxes) + 2), min(HEIGHT, max(b[3] for b in boxes) + 2))
    scale = min(WIDTH / (crop[2] - crop[0]), HEIGHT / (crop[3] - crop[1]))
    fitted_size = (round((crop[2] - crop[0]) * scale), round((crop[3] - crop[1]) * scale))
    offset = ((WIDTH - fitted_size[0]) // 2, (HEIGHT - fitted_size[1]) // 2)
    outputs = {}
    manifest = {"format": "LV_COLOR_FORMAT_RGB565A8", "layoutSource": LAYOUT_SOURCE,
                "size": [WIDTH, HEIGHT], "rgbStride": WIDTH * 2, "alphaStride": WIDTH,
                "commonSourceCrop": crop, "fittedSize": fitted_size, "offset": offset,
                "resample": "Pillow LANCZOS", "pillowVersion": pillow_version, "assets": []}
    for name, image in images.items():
        fitted = image.crop(crop).resize(fitted_size, Image.Resampling.LANCZOS)
        canvas = Image.new("RGBA", (WIDTH, HEIGHT))
        canvas.paste(fitted, offset)  # Preserve original alpha; don't apply it twice.
        data = encode(canvas)
        if len(data) != WIDTH * HEIGHT * 3 or data[WIDTH * HEIGHT * 2:] != canvas.getchannel("A").tobytes():
            raise SystemExit("RGB565A8 planar layout validation failed")
        symbol = name.replace("-", "_").removesuffix(".png")
        source_sha = sha((args.input_dir / name).read_bytes())
        output = c_source(symbol, data, source_sha).encode()
        outputs[symbol + ".c"] = output
        manifest["assets"].append({"source": "assets/rendering/" + name, "sourceSha256": source_sha,
                                   "symbol": symbol, "dataBytes": len(data), "dataSha256": sha(data),
                                   "cSha256": sha(output)})
    outputs["cat-sprites-manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    for name, content in outputs.items():
        destination = args.output_dir / name
        if args.check:
            if not destination.exists() or destination.read_bytes() != content:
                raise SystemExit("Generated asset differs: " + str(destination))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    # A known pixel pair independently pins endian/plane ordering.
    probe = Image.new("RGBA", (2, 1)); probe.putdata([(255, 0, 0, 7), (0, 255, 0, 255)])
    if encode(probe) != b"\x00\xf8\xe0\x07\x07\xff":
        raise SystemExit("Known-pixel encoding validation failed")
    print(("Verified" if args.check else "Generated") + " 2 original cat sprites; 216000 bytes total RGB565A8 data")


if __name__ == "__main__":
    main()
